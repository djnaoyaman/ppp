const { chromium } = require('playwright');
const fs=require('node:fs'); const path=require('node:path'); const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch();const page=await browser.newPage({viewport:{width:1200,height:630},deviceScaleFactor:1});
 await page.route('**/*',r=>new URL(r.request().url()).hostname==='127.0.0.1'?r.continue():r.abort());
 const lock=fs.existsSync('scripts/og-render-lock.json')?JSON.parse(fs.readFileSync('scripts/og-render-lock.json','utf8')):null;
 const report=[];fs.mkdirSync('test-artifacts/brand/og',{recursive:true});
 try{
  for(const file of fs.readdirSync('og/source').filter(f=>f.endsWith('.svg')).sort()){
   await page.goto('http://127.0.0.1:8765/og/source/'+file);await page.evaluate(()=>document.fonts.ready);
   const bounds=await page.locator('text').evaluateAll(nodes=>nodes.map(e=>{const b=e.getBBox();return {text:e.textContent,x:b.x,y:b.y,width:b.width,height:b.height}}));
   for(const b of bounds)assert.ok(b.x>=60&&b.x+b.width<=1140&&b.y>=290&&b.y+b.height<=600,JSON.stringify({file,b}));
   const output='og/'+file.replace('.svg','.png');await page.screenshot({path:output});
   const sha256=require('node:crypto').createHash('sha256').update(fs.readFileSync(output)).digest('hex');
   if(lock)assert.equal(sha256,lock[output],output+' regenerated bytes must match reviewed committed PNG');
   fs.copyFileSync(output,'test-artifacts/brand/'+output);report.push({file,output,bounds,sha256});
  }
 }finally{fs.writeFileSync('test-artifacts/brand/og-render-report.json',JSON.stringify(report,null,2));await browser.close()}
 assert.equal(report.length,41);console.log('PASS: 41 vector cards rendered to 1200x630 PNG; all text inside bounds');
})().catch(e=>{console.error(e);process.exit(1)});
